sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "tools"))

import experiment_2_tradeoffs as X          # noqa: E402
from generate import convergence as CV      # noqa: E402

OUT = ROOT / "docs" / "figures" / "ia-neutral-seat-distribution.png"
REPORT = ROOT / "docs" / "phase-2" / "phase-2-report.json"

STATE, ENSEMBLE = "IA", "v2"
#: The contest drawn. The other is measured too, because the span's upper edge
#: depends on the election.
CONTEST, ALTERNATE = "G20PRE", "G20USS"

#: Statewide two-party votes ``(D, R)`` per contest, as tools/prepare_data.py
#: (G20PRE) and tests/test_elections.py (both) assert them against the returns.
#: ``V`` comes from these; the Phase 2 report's G20PRE share is checked against them.
TWO_PARTY = {"G20PRE": (759_061, 897_672), "G20USS": (754_859, 864_997)}

#: The enacted plan's max-min population spread, docs/FEASIBILITY.md section 4,
#: and the spread PlanScore's copy of the plan carries (docs/cross-checks/).
ENACTED_SPREAD = 94

#: A non-sweep draw must sit within this fraction of the half-gap of its level.
MARGIN = 0.5

#: Float slack on the sweep window, which is exact in rational arithmetic.
SWEEP_SLACK = 1e-12

#: Draws dropped from the start of each chain for the warm-up sensitivity check.
#: D-035 discards none; this only reports what discarding would change.
BURN_IN_CHECK = 500

INK, MUTED, HUE, SURFACE = "#1a1a1a", "#6b6b6b", "#4a6fa5", "#ffffff"
BASELINE = "#8a8a8a"
#: Bar width, narrow enough that each bar's labels clear the next bar.
WIDTH = 0.5


def seat_levels(dem_share: float, k: int) -> dict[int, float]:
    """The |efficiency gap| a plan winning ``s`` of ``k`` seats sits at, ``s = 0..k``.

    Exact when every district casts the same number of two-party votes; a real
    plan sits off its level by its turnout imbalance. See the module docstring.
    """
    return {s: abs(2 * dem_share - 0.5 - s / k) for s in range(k + 1)}


def recover_seats(abs_gaps: list[float], levels: dict[int, float], total_votes: int,
                  margin: float = MARGIN) -> tuple[list[int], dict]:
    """Each draw's Democratic seat count, from its |efficiency gap|.

    Returns ``(seats, diagnostics)``. Raises ``ValueError`` -- refusing the whole
    sample, never one draw -- if any gap is not finite; if a draw read as a sweep
    (0 or ``k`` seats) is not inside the window the strict-majority threshold
    allows, ``[k/2T, k/T]`` from its level; or if any other draw sits more than
    ``margin`` of the half-gap from its level. The last condition is what keeps
    folded levels apart: nearness alone would accept a draw a hair from the
    midpoint of two levels.
    """
    if not abs_gaps:
        raise ValueError("no draws: there is no seat distribution to read")
    k = max(levels)
    ordered = sorted(levels.values())
    half_gap = min(b - a for a, b in zip(ordered, ordered[1:])) / 2
    sweep_low, sweep_high = k / (2 * total_votes), k / total_votes
    seats, residuals, worst, sweep_range = [], [], 0.0, [math.inf, -math.inf]
    for gap in abs_gaps:
        if not math.isfinite(gap):
            raise ValueError(f"a draw's efficiency gap is {gap!r}; there is no "
                             "seat count to read off it")
        s = min(levels, key=lambda n: abs(gap - levels[n]))
        residual = abs(gap - levels[s])
        if s in (0, k):
            if not sweep_low - SWEEP_SLACK <= residual <= sweep_high + SWEEP_SLACK:
                raise ValueError(
                    f"a draw read as {s} seats sits {residual:.3g} from its level, "
                    f"outside the [{sweep_low:.3g}, {sweep_high:.3g}] a sweep "
                    "allows: it is not a sweep, or the vote totals are wrong."
                )
            sweep_range = [min(sweep_range[0], residual), max(sweep_range[1], residual)]
        elif residual > margin * half_gap:
            raise ValueError(
                f"a draw sits {residual:.4f} from the {s}-seat level, more than "
                f"{margin} of the {half_gap:.4f} half-gap: its seat count cannot "
                "be read off its efficiency gap. Recount from the plan and the returns."
            )
        else:
            worst = max(worst, residual)
        seats.append(s)
        residuals.append(gap - levels[s])
    return seats, {"half_gap": half_gap, "max_residual": worst, "residuals": residuals,
                   "sweep_window": [sweep_low, sweep_high],
                   "sweep_residuals": sweep_range if sweep_range[0] <= sweep_range[1] else None}


def contest_distribution(chains, contest: str, k: int) -> dict:
    """Seat counts over the rectangle for one contest, with their uncertainty."""
    dem, rep = TWO_PARTY[contest]
    levels = seat_levels(dem / (dem + rep), k)
    key = f"abs_efficiency_gap@{contest}"
    per_chain, diagnostics = [], []
    for chain in chains:
        seats, diag = recover_seats([row[key] for row in chain.rows], levels, dem + rep)
        per_chain.append(seats)
        diagnostics.append(diag)
    pooled = [s for seats in per_chain for s in seats]
    outcomes = range(k + 1)
    counts = {s: pooled.count(s) for s in outcomes}
    shares = {s: counts[s] / len(pooled) for s in outcomes}

    def shares_of(draws):
        return {s: draws.count(s) / len(draws) for s in outcomes}

    halves = ([s for seats in per_chain for s in seats[:len(seats) // 2]],
              [s for seats in per_chain for s in seats[len(seats) // 2:]])
    residuals = [r for d in diagnostics for r in d["residuals"]]
    spread = {s: statistics.pstdev([r for x, r in zip(pooled, residuals) if x == s])
              for s in outcomes if 0 < s < k and counts[s] > 1}

    def indicator(s):
        return [[float(x == s) for x in seats] for seats in per_chain]

    # Monte Carlo standard error of each share from its own effective sample
    # size: the chains are autocorrelated, so len(pooled) is not the sample size.
    # An outcome one chain visits has no between-chain information at all, and
    # an ESS computed from it describes that chain, not the ensemble.
    seen_in = {s: sum(1 for seats in per_chain if s in seats) for s in outcomes}
    ess = {s: CV.ess(indicator(s)) if seen_in[s] >= 2 else None for s in outcomes}
    mcse = {s: math.sqrt(shares[s] * (1 - shares[s]) / ess[s]) if ess[s] else None
            for s in outcomes}
    series = [[float(x) for x in seats] for seats in per_chain]
    sweeps = [d["sweep_residuals"] for d in diagnostics if d["sweep_residuals"]]
    return {
        "contest": contest,
        "dem_vote_share": dem / (dem + rep),
        "levels": levels,
        "counts": counts,
        "shares": shares,
        "per_chain_shares": [{s: seats.count(s) / len(seats) for s in outcomes}
                             for seats in per_chain],
        "ess": ess,
        "mcse": mcse,
        "chains_seen": seen_in,
        "seat_count_split_rhat": CV.split_rhat(series),
        "seat_count_ess": CV.ess(series),
        "half_gap": diagnostics[0]["half_gap"],
        "max_residual": max(d["max_residual"] for d in diagnostics),
        "sweep_window": diagnostics[0]["sweep_window"],
        "sweep_residuals": ([min(s[0] for s in sweeps), max(s[1] for s in sweeps)]
                            if sweeps else None),
        "seats": per_chain,
        "start_seats": [seats[0] for seats in per_chain],
        "half_shares": [shares_of(halves[0]), shares_of(halves[1])],
        "after_burn_in": shares_of([s for seats in per_chain
                                    for s in seats[BURN_IN_CHECK:]]),
        "residual_sd": spread,
    }


def seat_distribution() -> dict:
    """The seat distribution under both contests, every value from committed files."""
    report = json.loads(REPORT.read_text())[STATE]
    if report["contest"] != CONTEST:
        raise ValueError(
            f"{REPORT} is computed on {report['contest']}, not {CONTEST}; its "
            "enacted seat count describes a different election."
        )
    partisan = report["partisan"]
    k = partisan["n_districts"]
    dem, rep = TWO_PARTY[CONTEST]
    if not math.isclose(dem / (dem + rep), partisan["dem_vote_share"], rel_tol=1e-12):
        raise ValueError(
            f"the asserted {CONTEST} totals give V = {dem / (dem + rep)!r}, the "
            f"Phase 2 report {partisan['dem_vote_share']!r}: one of them is stale."
        )

    requested, _ = X.ENSEMBLES[ENSEMBLE][STATE]
    rectangle = X.ENSEMBLES[ENSEMBLE]["rectangle"][STATE]
    spec = X.ensemble_spec(STATE, ENSEMBLE)
    chains = X.chains_from_draws(spec, X.draws_path(spec.prefix, ENSEMBLE),
                                 rectangle=rectangle)

    primary = contest_distribution(chains, CONTEST, k)
    alternate = contest_distribution(chains, ALTERNATE, k)

    rows = [row for chain in chains for row in chain.rows]
    seats = [s for chain_seats in primary["seats"] for s in chain_seats]
    as_equal = [s for row, s in zip(rows, seats)
                if row["population_spread"] <= ENACTED_SPREAD]
    distinct = {tuple(sorted(row.items())) for row in rows}
    enacted = partisan["dem_seats"]
    if not primary["counts"].get(enacted):
        raise ValueError(
            f"the enacted plan returns {enacted} D seats, which this ensemble never "
            "produced. That is a finding, not a plotting bug: annotate it "
            "deliberately rather than pointing at a bar that does not exist."
        )
    return {
        "n_districts": k,
        "rectangle": rectangle,
        "n_chains": len(chains),
        "n_chains_requested": requested,
        "n_draws": len(rows),
        "distinct_metric_rows": len(distinct),
        "primary": primary,
        "alternate": alternate,
        "contests_agree": sum(a == b for a, b in zip(
            seats, [s for chain_seats in alternate["seats"] for s in chain_seats])),
        "population_spread_median": statistics.median(
            row["population_spread"] for row in rows),
        "n_as_equal_as_enacted": len(as_equal),
        "as_equal_counts": {s: as_equal.count(s) for s in range(k + 1)},
        "enacted_dem_seats": enacted,
    }


def draw(d: dict, out: Path = OUT) -> None:
    p = d["primary"]
    k = d["n_districts"]
    xs = list(range(k + 1))
    pct = [100 * p["shares"][x] for x in xs]
    chain_pct = {x: [100 * c[x] for c in p["per_chain_shares"]] for x in xs}
    m = d["n_chains"]
    enacted = d["enacted_dem_seats"]

    fig, ax = plt.subplots(figsize=(8.2, 5.0), dpi=200)
    fig.patch.set_facecolor(SURFACE); ax.set_facecolor(SURFACE)

    bars = ax.bar(xs, pct, width=WIDTH, color=HUE, zorder=2)
    for b in bars:                       # 4px-equivalent rounded data-end
        b.set_linewidth(0); b.set_joinstyle("round")

    for x in xs:
        if p["counts"][x] == 0:
            ax.text(x, 1.2, "no draws", ha="center", va="bottom", color=MUTED,
                    fontsize=9, zorder=5)
            continue
        # two Monte Carlo standard errors, each share's own
        err = 2 * 100 * p["mcse"][x]
        ax.errorbar(x, pct[x], yerr=err, fmt="none", ecolor=INK, elinewidth=1.2,
                    capsize=4, capthick=1.2, zorder=4)
        # one dot per chain, spread sideways so none hides another, in a glyph
        # that reads the same on the bar and off it
        offsets = [(i - (m - 1) / 2) * 0.045 for i in range(m)]
        ax.scatter([x + o for o in offsets], chain_pct[x], s=16, color=SURFACE,
                   edgecolors=INK, linewidths=1.1, zorder=5)
        # offsets in points, not data units, so the labels cannot collide
        # however tall the axis ends up
        anchor = (x + WIDTH / 2 + 0.03, pct[x])
        ax.annotate(f"{pct[x]:.1f}%", xy=anchor, xytext=(0, 12),
                    textcoords="offset points", ha="left", va="bottom",
                    color=INK, fontsize=11, fontweight="bold", zorder=6)
        ax.annotate(f"{p['counts'][x]:,} draws", xy=anchor, xytext=(0, 1),
                    textcoords="offset points", ha="left", va="bottom",
                    color=MUTED, fontsize=8.5, zorder=6)

    # the enacted plan is a point on this axis: a mark under its seat count, and
    # the caveat in words, keyed by the same mark and placed above the seat
    # counts no draw reached, so the note never sits on a bar
    ax.plot([enacted], [-0.105], transform=ax.get_xaxis_transform(), marker="^",
            markersize=9, markerfacecolor=INK, markeredgecolor=INK, clip_on=False,
            zorder=6)
    ax.annotate(
        f"▲ Iowa's enacted plan returns {enacted} D seats,\n"
        f"as {pct[enacted]:.1f}% of these draws do. Not\n"
        "like-for-like: the draws are not held\n"
        "to the enacted plan's population\n"
        "equality, so this is not yet a finding.",
        xy=(0.635, 0.50), xycoords="axes fraction", ha="left", va="center",
        color=INK, fontsize=9, linespacing=1.35, zorder=6)

    ax.set_title("Seats in a neutral ReCom ensemble for Iowa", color=INK,
                 fontsize=13.5, fontweight="bold", loc="left", pad=34)
    ax.text(0, 1.075,
            f"Democratic seats of {k} under the 2020 presidential vote, in "
            f"{d['n_draws']:,} draws made without election data",
            transform=ax.transAxes, color=MUTED, fontsize=9.5, va="bottom")
    ax.text(0, 1.02,
            f"{d['n_chains']} of {d['n_chains_requested']} chains, cut to "
            f"{d['rectangle']:,} draws (D-035); effective sample "
            f"≈ {p['seat_count_ess']:.0f} for the seat count.  Dots: each chain.",
            transform=ax.transAxes, color=MUTED, fontsize=9.5, va="bottom")

    ax.set_xlabel(f"Democratic seats won (of {k})", color=MUTED, fontsize=10,
                  labelpad=24)
    ax.set_ylabel("share of draws", color=MUTED, fontsize=10)
    ax.set_xticks(xs)
    tops = [pct[x] + (2 * 100 * p["mcse"][x] if p["mcse"][x] else 0) for x in xs]
    ceiling = max(max(tops), max(max(v) for v in chain_pct.values()))
    ax.set_ylim(0, 5 * math.ceil((ceiling + 6) / 5))
    ax.set_xlim(-0.6, k + 0.45)
    ax.yaxis.set_major_formatter(lambda v, _: f"{v:.0f}%")
    ax.grid(axis="y", color="#e6e6e6", lw=0.8, zorder=0)
    ax.set_axisbelow(True)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color(BASELINE)
    ax.tick_params(colors=MUTED, length=0)

    span = [x for x in xs if p["counts"][x]]
    missing = [x for x in xs if not p["counts"][x]]
    alt = d["alternate"]
    alt_beyond = sum(alt["counts"][x] for x in xs if x > max(span))
    footer = [
        f"Support: {min(span)}–{max(span)} D seats of {k}"
        + (f"; no draw reached {' or '.join(map(str, missing))}." if missing else ".")
        + (f" Under the 2020 Senate vote, {alt_beyond} draws reach "
           f"{max(x for x in xs if alt['counts'][x])}." if alt_beyond else ""),
        f"Whiskers: ±2 Monte Carlo standard errors. Seat count split R-hat "
        f"{p['seat_count_split_rhat']:.3f}, outside CRITERIA §8's 1.00–1.01 band.",
        "Seats read off each draw's |efficiency gap| (D-039). "
        "Regenerate: tools/plot_seat_distribution.py",
    ]
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.tight_layout(rect=(0, 0.085, 1, 1))
    left = ax.get_position().x0
    for i, line in enumerate(footer):
        fig.text(left, 0.008 + 0.028 * (len(footer) - 1 - i), line, color=MUTED,
                 fontsize=8.5, va="bottom")
    fig.savefig(out, facecolor=SURFACE)
    plt.close(fig)


def summary_lines(d: dict) -> list[str]:
    lines = [
        f"{d['n_draws']:,} draws: {d['n_chains']} of {d['n_chains_requested']} chains "
        f"x {d['rectangle']:,} (D-035); at least {d['distinct_metric_rows']:,} "
        "distinct plans (distinct rows of committed metrics)",
    ]
    for key in ("primary", "alternate"):
        c = d[key]
        lines.append(
            f"{c['contest']}: levels "
            + ", ".join(f"{s}:{v:.4f}" for s, v in c["levels"].items())
        )
        lines.append(
            f"    V = {c['dem_vote_share']:.6f}; half-gap "
            f"{c['half_gap']:.4f}, largest non-sweep residual {c['max_residual']:.4f}; "
            f"sweeps {c['sweep_residuals']} inside {c['sweep_window']}; seat count "
            f"split R-hat {c['seat_count_split_rhat']:.4f}, ESS {c['seat_count_ess']:.1f}"
        )
        for s, n in c["counts"].items():
            chain = [100 * pc[s] for pc in c["per_chain_shares"]]
            mcse = (f"MCSE {100 * c['mcse'][s]:.2f} pts (ESS {c['ess'][s]:.0f})"
                    if c["mcse"][s] else
                    f"no MCSE: seen in {c['chains_seen'][s]} chain(s)" if n else "no draws")
            lines.append(f"    {s} D: {n:6,d}  {100 * c['shares'][s]:5.2f}%  {mcse}"
                         f"  chains {min(chain):.1f}-{max(chain):.1f}%")
        first, second = c["half_shares"]
        lines.append(
            "    first/second half of each chain: "
            + ", ".join(f"{s} D {100 * first[s]:.1f}/{100 * second[s]:.1f}%"
                        for s in c["counts"] if c["counts"][s])
            + f"; chains start at {c['start_seats']} seats"
        )
        lines.append(
            f"    dropping the first {BURN_IN_CHECK} draws of each chain: "
            + ", ".join(f"{s} D {100 * v:.2f}%" for s, v in c["after_burn_in"].items()
                        if c["counts"][s])
            + "; turnout-term SD by seat count "
            + ", ".join(f"{s}: {v:.4f}" for s, v in c["residual_sd"].items())
        )
    lines += [
        f"contests agree on {d['contests_agree']:,} of {d['n_draws']:,} draws",
        f"population spread: median {d['population_spread_median']:.0f} persons; "
        f"{d['n_as_equal_as_enacted']} draws at <= {ENACTED_SPREAD} "
        f"(seats {d['as_equal_counts']})",
        f"enacted plan: {d['enacted_dem_seats']} D seats ({CONTEST})",
    ]
    return lines


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args(argv)
    try:
        d = seat_distribution()
    except ValueError as refusal:
        print(f"refused: {refusal}", file=sys.stderr)
        return 1
    for line in summary_lines(d):
        print(line)
    draw(d, args.out)
    print("wrote", args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
