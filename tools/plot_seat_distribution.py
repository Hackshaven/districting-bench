def seat_levels(dem_share: float, k: int) -> dict[int, float]:
    """The |efficiency gap| a plan winning ``s`` of ``k`` seats sits at, ``s = 0..k``.

    Exact when every district casts the same number of two-party votes; a real
    plan sits off its level by its turnout imbalance. See the module docstring.
    """
    return {s: abs(2 * dem_share - 0.5 - s / k) for s in range(k + 1)}


def sweep_grid(k: int, total_votes: int) -> list[float]:
    """The votes a sweep sits above its level by: ``k - j/2``, ``j`` = T mod 2."""
    return [k - j / 2 for j in range(k + 1) if j % 2 == total_votes % 2]


def recover_seats(abs_gaps: list[float], levels: dict[int, float], total_votes: int,
                  margin: float = MARGIN) -> tuple[list[int], dict]:
    """Each draw's Democratic seat count, from its |efficiency gap|.

    Returns ``(seats, diagnostics)``. Raises ``ValueError`` -- refusing the whole
    sample, never one draw -- if there are no draws or any gap is not finite; if
    a draw read as a sweep (0 or ``k`` seats) does not sit above its level by a
    value on the half-vote grid :func:`sweep_grid` allows; or if any other draw
    sits more than ``margin`` of the half-gap from its level. The last condition
    is what keeps folded levels apart: nearness alone would accept a draw a hair
    from the midpoint of two levels.
    """
    if not abs_gaps:
        raise ValueError("no draws: there is no seat distribution to read")
    k = max(levels)
    ordered = sorted(levels.values())
    half_gap = min(b - a for a, b in zip(ordered, ordered[1:])) / 2
    grid = sweep_grid(k, total_votes)
    seats, residuals, worst, on_grid = [], [], 0.0, {}
    for gap in abs_gaps:
        if not math.isfinite(gap):
            raise ValueError(f"a draw's efficiency gap is {gap!r}, not finite: "
                             "there is no seat count to read off it")
        s = min(levels, key=lambda n: abs(gap - levels[n]))
        residual = gap - levels[s]
        if s in (0, k):
            votes = residual * total_votes
            nearest = min(grid, key=lambda g: abs(votes - g))
            if abs(votes - nearest) > GRID_SLACK:
                raise ValueError(
                    f"a draw read as {s} seats sits {votes:+.4f} votes off its "
                    f"level, not above it by one of the {grid} a sweep allows "
                    f"when the statewide total is "
                    f"{'odd' if total_votes % 2 else 'even'}: it is not a sweep, "
                    "or the vote totals are wrong."
                )
            on_grid[nearest] = on_grid.get(nearest, 0) + 1
        elif abs(residual) > margin * half_gap:
            raise ValueError(
                f"a draw sits {abs(residual):.4f} from the {s}-seat level, more "
                f"than {margin} of the {half_gap:.4f} half-gap: its seat count "
                "cannot be read off its efficiency gap. Recount from the plan and "
                "the returns."
            )
        else:
            worst = max(worst, abs(residual))
        seats.append(s)
        residuals.append(residual)
    return seats, {"half_gap": half_gap, "max_residual": worst, "residuals": residuals,
                   "sweep_grid": grid, "sweeps_on_grid": on_grid}


def batch_means_tau(series: list[list[float]], b: int) -> float:
    """Integrated autocorrelation time from non-overlapping batches of ``b`` draws."""
    pooled = [x for s in series for x in s]
    mean = statistics.fmean(pooled)
    variance = statistics.pvariance(pooled)
    batches = [statistics.fmean(s[j * b:(j + 1) * b])
               for s in series for j in range(len(s) // b)]
    return b * math.fsum((m - mean) ** 2 for m in batches) / len(batches) / variance


def short_run_se(all_seats: list[list[int]], s: int, share: float, tau: float,
                 chains: int = V010_CHAINS, length: int = V010_LENGTH) -> dict:
    """The standard error of a ``chains`` x ``length`` estimate of the share at ``s`` seats.

    Three ways, from the committed chains: ``windows``, the spread of every
    non-overlapping ``length``-draw window of every chain; ``starts``, the
    spread of each chain's first ``length`` draws, which is how v0.1.0's chains
    ran; and ``asymptotic``, from this share's autocorrelation time ``tau`` on
    the rectangle.
    """
    def share_of(seats):
        return sum(1 for x in seats if x == s) / len(seats)
    windows = [share_of(seats[j * length:(j + 1) * length])
               for seats in all_seats for j in range(len(seats) // length)]
    starts = [share_of(seats[:length]) for seats in all_seats if len(seats) >= length]
    root = math.sqrt(chains)
    return {"windows": statistics.stdev(windows) / root, "n_windows": len(windows),
            "starts": statistics.stdev(starts) / root, "n_starts": len(starts),
            "asymptotic": math.sqrt(share * (1 - share) * tau / (chains * length))}


def contest_distribution(chains, contest: str, k: int, all_rows=None) -> dict:
    """Seat counts over the rectangle for one contest, with their uncertainty.

    ``all_rows`` is every committed draw of every chain, not only the rectangle;
    it is used for the batch-means and short-run standard errors, which need
    dependence longer than the rectangle can show, and for each chain's fate.
    """
    dem, rep = TWO_PARTY[contest]
    total = dem + rep
    levels = seat_levels(dem / total, k)
    key = f"abs_efficiency_gap@{contest}"
    per_chain, diagnostics = [], []
    for chain in chains:
        seats, diag = recover_seats([row[key] for row in chain.rows], levels, total)
        per_chain.append(seats)
        diagnostics.append(diag)
    pooled = [s for seats in per_chain for s in seats]
    outcomes = range(k + 1)
    counts = {s: pooled.count(s) for s in outcomes}
    shares = {s: counts[s] / len(pooled) for s in outcomes}

    def shares_of(draws):
        return {s: draws.count(s) / len(draws) for s in outcomes}

    halves = ([s for seats in per_chain for s in seats[:len(seats) // 2]],
              [s for seats in per_chain for s in seats[len(seats) // 2:]])
    residuals = [r for d in diagnostics for r in d["residuals"]]
    spread = {s: statistics.pstdev([r for x, r in zip(pooled, residuals) if x == s])
              for s in outcomes if 0 < s < k and counts[s] > 1}

    def indicator(s, chain_seats=per_chain):
        return [[float(x == s) for x in seats] for seats in chain_seats]

    # Monte Carlo standard error of each share from its own effective sample
    # size: the chains are autocorrelated, so len(pooled) is not the sample size.
    # An outcome one chain visits has no between-chain information at all, and
    # an ESS computed from it describes that chain, not the ensemble.
    seen_in = {s: sum(1 for seats in per_chain if s in seats) for s in outcomes}
    ess, outcome_rhat = {}, {}
    for s in outcomes:
        value = CV.ess(indicator(s)) if seen_in[s] >= 2 else None
        ess[s] = value if value is not None and math.isfinite(value) and value > 0 else None
        outcome_rhat[s] = CV.split_rhat(indicator(s)) if seen_in[s] >= 2 else None
    mcse = {s: math.sqrt(shares[s] * (1 - shares[s]) / ess[s]) if ess[s] else None
            for s in outcomes}

    batch, short_run, all_seats = {}, {}, None
    if all_rows is not None:
        all_seats = [recover_seats([row[key] for row in rows], levels, total)[0]
                     if rows else [] for rows in all_rows]
        everything = [seats for seats in all_seats if seats]
        for s in outcomes:
            if 0 < counts[s] < len(pooled):
                taus = {b: batch_means_tau(indicator(s, everything), b) for b in BATCH_SIZES}
                batch[s] = {b: math.sqrt(shares[s] * (1 - shares[s]) * tau / len(pooled))
                            for b, tau in taus.items()}
                if ess[s]:
                    short_run[s] = short_run_se(everything, s, shares[s],
                                                len(pooled) / ess[s])

    series = [[float(x) for x in seats] for seats in per_chain]
    on_grid = {}
    for d in diagnostics:
        for g, n in d["sweeps_on_grid"].items():
            on_grid[g] = on_grid.get(g, 0) + n
    return {
        "contest": contest,
        "dem_vote_share": dem / total,
        "total_votes": total,
        "levels": levels,
        "counts": counts,
        "shares": shares,
        "per_chain_shares": [shares_of(seats) for seats in per_chain],
        "per_chain_half_shares": [(shares_of(seats[:len(seats) // 2]),
                                   shares_of(seats[len(seats) // 2:]))
                                  for seats in per_chain],
        "ess": ess,
        "mcse": mcse,
        "outcome_rhat": outcome_rhat,
        "batch_means_mcse": batch,
        "short_run_se": short_run,
        "chains_seen": seen_in,
        "seat_count_split_rhat": CV.split_rhat(series),
        "seat_count_ess": CV.ess(series),
        "half_gap": diagnostics[0]["half_gap"],
        "max_residual": max(d["max_residual"] for d in diagnostics),
        "sweep_grid": diagnostics[0]["sweep_grid"],
        "sweeps_on_grid": dict(sorted(on_grid.items())),
        "seats": per_chain,
        "all_seats": all_seats,
        "start_seats": [seats[0] for seats in per_chain],
        "half_shares": [shares_of(halves[0]), shares_of(halves[1])],
        "after_burn_in": shares_of([s for seats in per_chain
                                    for s in seats[BURN_IN_CHECK:]]),
        "warm_up_counts": [{s: seats[:BURN_IN_CHECK].count(s) for s in outcomes}
                           for seats in per_chain],
        "residual_sd": spread,
    }


def closest_district(report: dict) -> tuple[int, float]:
    """The enacted plan's district nearest 50%, as the Phase 2 report's caveat states it.

    The report records it only inside a caveat sentence, so it is read from
    there; a report without it is refused rather than drawn without the caveat.
    """
    for caveat in report["trust"]["caveats"]:
        found = re.search(r"district (\d+) sits at (0\.\d+)", caveat)
        if found:
            return int(found.group(1)), float(found.group(2))
    raise ValueError(f"{REPORT} no longer states the enacted plan's closest "
                     "district, which the figure's caveat quotes")


def chain_indices(spec, chains) -> list[int]:
    """Each chain's index, recovered from its seed: the loader keeps the seed only."""
    by_seed = {X.seeds.derive(X.MASTER_SEED, f"exp2-{spec.key.lower()}", i): i
               for i in range(spec.chains)}
    missing = [chain.seed for chain in chains if chain.seed not in by_seed]
    if missing:
        raise ValueError(f"seeds {missing} derive from no chain index of {spec.key}")
    return [by_seed[chain.seed] for chain in chains]


def prefix_match(rows: list[dict], before: list[dict]) -> tuple[int, int]:
    """How many of ``before``'s rows a chain repeats in place, and how many there are."""
    return sum(a == b for a, b in zip(rows, before)), len(before)


def zero_share(seats: list[int]) -> tuple[float | None, int]:
    """The share of ``seats`` at 0, and how many draws it rests on."""
    return (seats.count(0) / len(seats) if seats else None), len(seats)


def seat_distribution() -> dict:
    """The seat distribution under both contests, every value from committed files."""
    report = json.loads(REPORT.read_text())[STATE]
    if report["contest"] != CONTEST:
        raise ValueError(
            f"{REPORT} is computed on {report['contest']}, not {CONTEST}; its "
            "enacted seat count describes a different election."
        )
    partisan = report["partisan"]
    k = partisan["n_districts"]
    dem, rep = TWO_PARTY[CONTEST]
    if not math.isclose(dem / (dem + rep), partisan["dem_vote_share"], rel_tol=1e-12):
        raise ValueError(
            f"the asserted {CONTEST} totals give V = {dem / (dem + rep)!r}, the "
            f"Phase 2 report {partisan['dem_vote_share']!r}: one of them is stale."
        )

    spec = X.ensemble_spec(STATE, ENSEMBLE)
    if spec.k != k:
        raise ValueError(f"the ensemble draws {spec.k} districts and the Phase 2 "
                         f"report's plan has {k}")
    rectangle = X.ENSEMBLES[ENSEMBLE]["rectangle"][STATE]
    every = X.chains_from_draws(spec, X.draws_path(spec.prefix, ENSEMBLE))
    chains = X.chains_from_draws(spec, X.draws_path(spec.prefix, ENSEMBLE),
                                 rectangle=rectangle)
    every_index, index = chain_indices(spec, every), chain_indices(spec, chains)
    all_rows = [chain.rows for chain in every]

    primary = contest_distribution(chains, CONTEST, k, all_rows)
    alternate = contest_distribution(chains, ALTERNATE, k)

    enacted = partisan["dem_seats"]
    if not primary["counts"].get(enacted):
        raise ValueError(
            f"the enacted plan returns {enacted} D seats, which this ensemble never "
            "produced. Locating it needs its own annotation, not a pointer to a "
            "bar that does not exist."
        )

    # The 2-seat share on every rectangle tools/convergence_rectangle.py offers:
    # the chosen one drops chains for dying early, and this shows what it costs.
    by_rectangle = {}
    lengths = [len(rows) for rows in all_rows]
    for r in json.loads(RECTANGLES.read_text())["rectangles"]:
        prefix = r["prefix_length"]
        kept = [seats[:prefix] for seats in primary["all_seats"] if len(seats) >= prefix]
        pooled = [s for seats in kept for s in seats]
        by_rectangle[(len(kept), prefix)] = pooled.count(2) / len(pooled)

    # v2's chains continue v1's from the same seeds, so v1's draws are their
    # first rows: no part of the rectangle is a fresh start.
    earlier_spec = X.ensemble_spec(STATE, EARLIER)
    earlier = {chain.seed: chain.rows for chain in X.chains_from_draws(
        earlier_spec, X.draws_path(earlier_spec.prefix, EARLIER))}
    earlier_prefix = {i: prefix_match(chain.rows, earlier.get(chain.seed, []))
                      for i, chain in zip(index, chains)}

    rows = [row for chain in chains for row in chain.rows]
    where = [(i, j) for i, chain in zip(index, chains) for j in range(len(chain.rows))]
    seats = [s for chain_seats in primary["seats"] for s in chain_seats]
    alt_seats = [s for chain_seats in alternate["seats"] for s in chain_seats]
    top = max(s for s in range(k + 1) if primary["counts"][s])
    beyond = [(w, row) for w, row, s in zip(where, rows, alt_seats) if s > top]
    as_equal = [(w, row, s) for w, row, s in zip(where, rows, seats)
                if row["population_spread"] <= ENACTED_SPREAD]
    as_equal_enacted = [(w, row) for w, row, s in as_equal if s == enacted]

    # The enacted plan's compactness, against the draws': ReCom leans compact,
    # and the enacted outcome is commoner among the draws as uncompact as it.
    cut = report["compactness"]["cut_edges"]

    def by_cut(pairs):
        pairs = list(pairs)
        return (zero_share([s for row, s in pairs if row["cut_edges"] >= cut]),
                zero_share([s for row, s in pairs if row["cut_edges"] < cut]))

    late = [(row, s) for chain, chain_seats in zip(chains, primary["seats"])
            for row, s in list(zip(chain.rows, chain_seats))[BURN_IN_CHECK:]]
    at_or_above, below = by_cut(zip(rows, seats))
    late_above, late_below = by_cut(late)
    def cut_edge_profile(selected):
        edges = [row["cut_edges"] for row in selected]
        return (statistics.fmean(edges), sum(1 for e in edges if e >= cut) / len(edges),
                len(edges))

    compactness = {
        "enacted_cut_edges": cut,
        "more_compact_share": sum(1 for row in rows if row["cut_edges"] < cut) / len(rows),
        # population-tight draws against the rest: how much of the compactness
        # gap follows from the population gap
        "as_equal_profile": cut_edge_profile([row for _, row, _ in as_equal]),
        "rest_profile": cut_edge_profile([row for row in rows
                                          if row["population_spread"] > ENACTED_SPREAD]),
        "at_or_above": at_or_above,
        "below": below,
        "at_or_above_after_burn_in": late_above,
        "below_after_burn_in": late_below,
        "per_chain": [(i, *(share for share, _ in by_cut(zip(chain.rows, cs))))
                      for i, chain, cs in zip(index, chains, primary["seats"])],
    }

    district, district_share = closest_district(report)
    return {
        "state": STATE,
        "n_districts": k,
        "rectangle": rectangle,
        "chain_index": index,
        "n_chains": len(chains),
        "n_chains_requested": len(every),
        "n_chains_never_started": sum(1 for n in lengths if n == 0),
        "n_chains_stopped_early": sum(1 for n in lengths if 0 < n < rectangle),
        "n_draws": len(rows),
        "n_rows_committed": sum(lengths),
        "distinct_metric_rows": len({tuple(sorted(row.items())) for row in rows}),
        "distinct_metric_rows_committed": len({tuple(sorted(row.items()))
                                               for rows_ in all_rows for row in rows_}),
        "repeats": sum(1 for chain in chains for a, b in zip(chain.rows, chain.rows[1:])
                       if a == b),
        "chain_fates": [
            {"chain": i, "n_draws": len(chain.rows), "completed": chain.completed,
             "last_seats": seats_[-1] if seats_ else None,
             "two_seat_share": seats_.count(2) / len(seats_) if seats_ else None}
            for i, chain, seats_ in zip(every_index, every, primary["all_seats"])],
        "earlier_prefix": earlier_prefix,
        "primary": primary,
        "alternate": alternate,
        "contests_agree": sum(a == b for a, b in zip(seats, alt_seats)),
        "alternate_beyond": {
            "seats": top + 1,
            "draws": [w for w, _ in beyond],
            "distinct": len({tuple(sorted(row.items())) for _, row in beyond}),
        },
        "two_seat_share_by_rectangle": by_rectangle,
        "population_spread_median": statistics.median(
            row["population_spread"] for row in rows),
        "n_as_equal_as_enacted": len(as_equal),
        "as_equal_counts": {s: sum(1 for *_, x in as_equal if x == s) for s in range(k + 1)},
        "as_equal_enacted_draws": [w for w, _ in as_equal_enacted],
        "as_equal_enacted_distinct": len({tuple(sorted(row.items()))
                                          for _, row in as_equal_enacted}),
        "compactness": compactness,
        "enacted_dem_seats": enacted,
        "enacted_closest_district": district,
        "enacted_closest_share": district_share,
    }


def chain_offsets(m: int) -> list[float]:
    """Sideways positions for ``m`` chain dots: clear of the centre, where the
    whisker runs, and 0.06 apart, so no dot covers another."""
    side = [0.09 + 0.06 * j for j in range(m // 2)]
    return [-x for x in reversed(side)] + ([0.0] if m % 2 else []) + side


def span_text(draws: list[tuple[int, int]], window: int) -> str:
    """Where a handful of draws sit, in words: one chain and an early window, or not.
    The figure has no key to chain indices, so it names none."""
    chains = {i for i, _ in draws}
    if len(chains) == 1:
        last = max(j for _, j in draws)
        return (f"all in one chain's first {window} draws" if last < window
                else "all in one chain")
    return f"in {len(chains)} chains"


def share_text(share: float) -> str:
    """A share to one decimal, without rounding a share above zero down to it."""
    return "<0.1%" if 0 < share < 0.0005 else f"{100 * share:.1f}%"


def figure_text(d: dict) -> dict:
    """Every string the figure prints, built from the values it describes."""
    p, alt = d["primary"], d["alternate"]
    k, state = d["n_districts"], STATE_NAMES[d["state"]]
    xs = range(k + 1)
    enacted = d["enacted_dem_seats"]
    chain_range = [100 * c[enacted] for c in p["per_chain_shares"]]
    span = [x for x in xs if p["counts"][x]]
    missing = [x for x in xs if not p["counts"][x]]
    rhat = p["seat_count_split_rhat"]
    where = "inside" if RHAT_BAND[0] <= rhat <= RHAT_BAND[1] else "outside"
    per_split = p["seat_count_ess"] / (2 * d["n_chains"])
    compact = d["compactness"]
    high, _ = compact["at_or_above"]
    low, _ = compact["below"]
    commoner = "commoner" if high > low else "rarer"
    blocks = [100 * v for b in p["batch_means_mcse"].values() for v in b.values()]
    two = p["batch_means_mcse"].get(2, {})

    labels = {}
    for x in xs:
        if not p["counts"][x]:
            labels[x] = ("", "no draws")
        elif p["mcse"][x]:
            labels[x] = (share_text(p["shares"][x]),
                         f"±{200 * p['mcse'][x]:.1f} pts\n{p['counts'][x]:,} draws")
        else:
            why = "1 chain only" if p["chains_seen"][x] < 2 else "no standard error"
            labels[x] = (share_text(p["shares"][x]), f"{why}\n{p['counts'][x]:,} draws")

    beyond = d["alternate_beyond"]
    reach = ""
    if beyond["draws"]:
        higher = any(alt["counts"][x] for x in xs if x > beyond["seats"])
        plans = f"{beyond['distinct']} distinct plan{'s' if beyond['distinct'] > 1 else ''}"
        reach = (f" Under the {CONTEST_NAMES[alt['contest']]} vote, "
                 f"{len(beyond['draws'])} draws reach {beyond['seats']}"
                 f"{'+' if higher else ''}: {plans}, "
                 f"{span_text(beyond['draws'], BURN_IN_CHECK)}.")
    if two:
        se_low, se_high = min(two.values()), max(two.values())
        block = (f"; block means over all {d['n_rows_committed']:,} committed draws put "
                 f"the 2-seat share's standard error at {100 * se_low:.1f}–"
                 f"{100 * se_high:.1f} pts")
    elif blocks:
        block = f"; block means give {min(blocks):.1f}–{max(blocks):.1f} pts"
    else:
        block = ""
    # one paragraph, wrapped by width rather than by sentence, so a longer
    # value cannot push a line off the canvas
    footer = textwrap.wrap(
        f"Range in these draws: {min(span)}–{max(span)} D seats of {k}"
        + (f"; none reached {' or '.join(map(str, missing))}." if missing else ".") + reach
        + " Seats are read off each draw's |efficiency gap| (D-039). Dots: each chain's "
        "share. Whiskers and ±: 2 Monte Carlo standard errors of the pooled share, from "
        f"its effective sample size{block}. Seat count split R-hat {rhat:.3f}, {where} "
        f"CRITERIA §8's {RHAT_BAND[0]:.2f}–{RHAT_BAND[1]:.2f} band"
        + (f", on {per_split:.0f} effective draws per split chain, below the "
           f"{RHAT_MIN_ESS_PER_SPLIT} Vehtari et al. (2021) ask for before relying on it"
           if per_split < RHAT_MIN_ESS_PER_SPLIT else "")
        + ". Regenerate: tools/plot_seat_distribution.py, from committed files only.",
        FOOTER_WIDTH)
    return {
        "title": f"Seats in a neutral ReCom ensemble for {state}",
        "subtitle": [
            f"Democratic seats of {k} under the {CONTEST_NAMES[p['contest']]} vote, "
            f"in {d['n_draws']:,} ReCom draws made without election data",
            f"{d['n_chains']} of {d['n_chains_requested']} chains, each cut to its first "
            f"{d['rectangle']:,} draws (D-035); {d['n_chains_never_started']} never "
            f"started and {d['n_chains_stopped_early']} stopped before {d['rectangle']:,}",
            f"About {p['seat_count_ess']:.0f} effective draws for the seat count",
        ],
        "labels": labels,
        "enacted_x": enacted,
        # wrapped by width like the footer, so longer values cannot push it
        # off the canvas
        "note": "\n".join(textwrap.wrap(
            f"▲ {state}'s enacted plan returns {enacted} D seats, as "
            f"{share_text(p['shares'][enacted])} of these draws do "
            f"({min(chain_range):.1f}–{max(chain_range):.1f}% across chains); its "
            f"{enacted} turns on one district at {100 * d['enacted_closest_share']:.1f}% D. "
            "Not like-for-like: the draws are not held to its population equality. "
            f"The plan is also less compact than {100 * compact['more_compact_share']:.0f}% of "
            f"them, and {enacted} seats is {commoner} among less compact draws. "
            "Not yet a finding.", NOTE_WIDTH)),
        "footer": footer,
    }


def draw(d: dict, out: Path = OUT) -> dict:
    """Draw the figure to ``out``, and return what was placed, for the tests."""
    p = d["primary"]
    k = d["n_districts"]
    xs = list(range(k + 1))
    pct = [100 * p["shares"][x] for x in xs]
    chain_pct = {x: [100 * c[x] for c in p["per_chain_shares"]] for x in xs}
    text = figure_text(d)
    offsets = chain_offsets(d["n_chains"])
    placed = {"whiskers": {}, "label_y": {}}

    fig, ax = plt.subplots(figsize=(8.2, 6.0), dpi=200)
    fig.patch.set_facecolor(SURFACE); ax.set_facecolor(SURFACE)

    bars = ax.bar(xs, pct, width=WIDTH, color=HUE, zorder=2)
    for b in bars:
        b.set_linewidth(0)
    placed["bars"] = [b.get_height() for b in bars]

    for x in xs:
        bold, muted = text["labels"][x]
        if not p["counts"][x]:
            ax.text(x, 1.2, muted, ha="center", va="bottom", color=MUTED,
                    fontsize=9, zorder=5)
            continue
        err = 2 * 100 * p["mcse"][x] if p["mcse"][x] else 0.0
        if err:
            whisker = ax.errorbar(x, pct[x], yerr=err, fmt="none", ecolor=INK,
                                  elinewidth=1.2, capsize=4, capthick=1.2, zorder=4)
            (low, high), = [(a[1], b[1]) for a, b in whisker.lines[2][0].get_segments()]
            placed["whiskers"][x] = (high - low) / 2
        # one dot per chain, beside the whisker rather than on it, in a glyph
        # that reads the same on the bar and off it
        ax.scatter([x + o for o in offsets], chain_pct[x], s=16, color=SURFACE,
                   edgecolors=INK, linewidths=1.1, zorder=5, clip_on=False)
        # labels centred over the bar, above everything drawn there, with
        # offsets in points so they cannot collide however tall the axis is
        top = max([pct[x] + err] + chain_pct[x])
        placed["label_y"][x] = top
        ax.annotate(muted, xy=(x, top), xytext=(0, 5), textcoords="offset points",
                    ha="center", va="bottom", color=MUTED, fontsize=8.5,
                    linespacing=1.2, zorder=6)
        ax.annotate(bold, xy=(x, top), xytext=(0, 29), textcoords="offset points",
                    ha="center", va="bottom", color=INK, fontsize=11,
                    fontweight="bold", zorder=6)

    # the enacted plan is a point on this axis: a mark under its seat count, and
    # the caveats in words, keyed by the same mark and set to the right of the
    # last seat count any draw reached
    marker, = ax.plot([text["enacted_x"]], [-0.095], transform=ax.get_xaxis_transform(),
                      marker="^", markersize=9, markerfacecolor=INK, markeredgecolor=INK,
                      clip_on=False, zorder=6)
    placed["marker_x"] = marker.get_xdata()[0]
    note = ax.annotate(text["note"], xy=(max(x for x in xs if p["counts"][x]) + WIDTH / 2
                                         + 0.33, 0.5),
                       xycoords=("data", "axes fraction"), ha="left", va="center",
                       color=INK, fontsize=9.5, linespacing=1.25, zorder=6,
                       bbox=dict(facecolor=SURFACE, edgecolor="none", pad=2))
    placed["note_x"] = note.xy[0]

    ax.set_title(text["title"], color=INK, fontsize=13.5, fontweight="bold",
                 loc="left", pad=52)
    for i, line in enumerate(text["subtitle"]):
        ax.text(0, 1.02 + 0.05 * (len(text["subtitle"]) - 1 - i), line,
                transform=ax.transAxes, color=MUTED, fontsize=9.5, va="bottom")

    ax.set_xlabel(f"Democratic seats won (of {k})", color=MUTED, fontsize=10,
                  labelpad=24)
    ax.set_ylabel("share of draws", color=MUTED, fontsize=10)
    ax.set_xticks(xs)
    ceiling = max(placed["label_y"].values())
    ax.set_ylim(0, 5 * math.ceil((ceiling + 16) / 5))
    ax.set_xlim(-0.6, k + 0.45)
    ax.yaxis.set_major_formatter(lambda v, _: f"{v:.0f}%")
    ax.grid(axis="y", color="#e6e6e6", lw=0.8, zorder=0)
    ax.set_axisbelow(True)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color(BASELINE)
    ax.tick_params(colors=MUTED, length=0)

    out.parent.mkdir(parents=True, exist_ok=True)
    footer = text["footer"]
    fig.tight_layout(rect=(0, 0.03 + 0.024 * len(footer), 1, 1))
    left = ax.get_position().x0
    for i, line in enumerate(footer):
        fig.text(left, 0.008 + 0.024 * (len(footer) - 1 - i), line, color=MUTED,
                 fontsize=9, va="bottom")
    fig.savefig(out, facecolor=SURFACE)
    plt.close(fig)
    return placed


def _pct(value) -> str:
    return "n/a" if value is None else f"{100 * value:.2f}%"


def summary_lines(d: dict) -> list[str]:
    """Every number docs/progress.md quotes about this sample, in print."""
    lines = [
        f"{d['n_draws']:,} draws: {d['n_chains']} of {d['n_chains_requested']} chains "
        f"({d['n_chains_never_started']} never started, {d['n_chains_stopped_early']} "
        f"stopped before {d['rectangle']:,}) x {d['rectangle']:,} (D-035), chains "
        f"{d['chain_index']}; at least {d['distinct_metric_rows']:,} distinct plans "
        f"(distinct rows of committed metrics; {d['distinct_metric_rows_committed']:,} "
        f"in all {d['n_rows_committed']:,} committed rows)",
        f"draws repeating the draw before them: {d['repeats']:,} of {d['n_draws']:,} "
        f"({100 * d['repeats'] / d['n_draws']:.1f}%)",
        "each rectangle chain's first rows against v1's draws from the same seed: "
        + ", ".join(f"chain {i} {same:,} of {n:,} identical"
                    for i, (same, n) in d["earlier_prefix"].items()),
    ]
    for key in ("primary", "alternate"):
        c = d[key]
        lines.append(
            f"{c['contest']}: levels "
            + ", ".join(f"{s}:{v:.4f}" for s, v in c["levels"].items())
            + f"; V = {c['dem_vote_share']:.6f}, T = {c['total_votes']:,}"
        )
        lines.append(
            f"    half-gap {c['half_gap']:.4f}, largest non-sweep residual "
            f"{c['max_residual']:.4f}; sweeps on the half-vote grid "
            f"{c['sweeps_on_grid']} (allowed {c['sweep_grid']}); seat count "
            f"split R-hat {c['seat_count_split_rhat']:.4f}, ESS {c['seat_count_ess']:.1f}"
        )
        for s, n in c["counts"].items():
            chain = [100 * pc[s] for pc in c["per_chain_shares"]]
            mcse = (f"MCSE {100 * c['mcse'][s]:.2f} pts (ESS {c['ess'][s]:.0f}, "
                    f"R-hat {c['outcome_rhat'][s]:.4f})" if c["mcse"][s] else
                    f"no MCSE: seen in {c['chains_seen'][s]} chain(s)" if n else "no draws")
            batch = c["batch_means_mcse"].get(s)
            batch_text = ("; block means over all draws "
                          + "/".join(f"{100 * v:.2f}" for v in batch.values())
                          + f" pts at b={'/'.join(map(str, batch))}") if batch else ""
            lines.append(f"    {s} D: {n:6,d}  {100 * c['shares'][s]:5.2f}%  {mcse}"
                         f"  chains {min(chain):.1f}-{max(chain):.1f}%{batch_text}")
        if c["all_seats"]:
            everything = [s for seats in c["all_seats"] for s in seats]
            lines.append(f"    all {len(everything):,} committed rows: "
                         + ", ".join(f"{s} D {everything.count(s):,}" for s in c["counts"]))
        for s, se in c["short_run_se"].items():
            lines.append(
                f"    {s} D, standard error of a {V010_CHAINS}-chain, {V010_LENGTH}-draw "
                f"estimate: {100 * se['windows']:.2f} pts from {se['n_windows']} windows, "
                f"{100 * se['starts']:.2f} from {se['n_starts']} chain starts, "
                f"{100 * se['asymptotic']:.2f} asymptotic"
            )
        first, second = c["half_shares"]
        lines.append(
            "    first/second half of the rectangle: "
            + ", ".join(f"{s} D {100 * first[s]:.1f}/{100 * second[s]:.1f}%"
                        for s in c["counts"] if c["counts"][s])
            + f"; chains start at {c['start_seats']} seats"
        )
        lines.append(
            "    by chain, 1 D / 2 D share (2 D over first/second half): "
            + "; ".join(f"{i}: {100 * pc[1]:.1f}/{100 * pc[2]:.1f}% "
                        f"({100 * h[0][2]:.1f}/{100 * h[1][2]:.1f}%)"
                        for i, pc, h in zip(d["chain_index"], c["per_chain_shares"],
                                            c["per_chain_half_shares"]))
        )
        lines.append(
            f"    draws by seats in each chain's first {BURN_IN_CHECK}: "
            + "; ".join(f"{i}: " + ", ".join(f"{s} D {n}" for s, n in w.items() if n)
                        for i, w in zip(d["chain_index"], c["warm_up_counts"]))
        )
        lines.append(
            f"    dropping the first {BURN_IN_CHECK} draws of each chain: "
            + ", ".join(f"{s} D {100 * v:.2f}%" for s, v in c["after_burn_in"].items()
                        if c["counts"][s])
            + "; turnout-term SD by seat count "
            + ", ".join(f"{s}: {v:.4f}" for s, v in c["residual_sd"].items())
        )
    beyond = d["alternate_beyond"]
    compact = d["compactness"]
    lines += [
        f"{d['alternate']['contest']} draws at {beyond['seats']}+ D seats: "
        f"{len(beyond['draws'])}, {beyond['distinct']} distinct plans, at (chain, draw) "
        f"{beyond['draws']}",
        "2-seat share by rectangle (chains x draws): "
        + ", ".join(f"{m}x{n}: {100 * v:.1f}%"
                    for (m, n), v in d["two_seat_share_by_rectangle"].items()),
        "chain fates (index: draws, seats at the last draw, 2 D share over all its draws): "
        + "; ".join(f"{f['chain']}: {f['n_draws']:,}"
                    + (" completed" if f["completed"] else "")
                    + (f", ends at {f['last_seats']}, {100 * f['two_seat_share']:.1f}%"
                       if f["n_draws"] else "")
                    for f in d["chain_fates"]),
        f"contests agree on {d['contests_agree']:,} of {d['n_draws']:,} draws "
        f"({100 * d['contests_agree'] / d['n_draws']:.1f}%)",
        f"population spread: median {d['population_spread_median']:.0f} persons; "
        f"{d['n_as_equal_as_enacted']} draws at <= {ENACTED_SPREAD} "
        f"({100 * d['n_as_equal_as_enacted'] / d['n_draws']:.2f}%; seats "
        f"{d['as_equal_counts']}); those at {d['enacted_dem_seats']} D: "
        f"{d['as_equal_enacted_distinct']} distinct, at {d['as_equal_enacted_draws']}",
        f"cut edges: enacted plan {compact['enacted_cut_edges']}; {d['enacted_dem_seats']} D "
        f"share {_pct(compact['at_or_above'][0])} of {compact['at_or_above'][1]:,} draws "
        f"at >= {compact['enacted_cut_edges']}, {_pct(compact['below'][0])} of "
        f"{compact['below'][1]:,} below; after dropping {BURN_IN_CHECK} per chain "
        f"{_pct(compact['at_or_above_after_burn_in'][0])} against "
        f"{_pct(compact['below_after_burn_in'][0])}; by chain (at or above / below) "
        + ", ".join(f"{i}: {_pct(a)}/{_pct(b)}" for i, a, b in compact["per_chain"]),
        f"    {_pct(compact['more_compact_share'])} of draws have fewer cut edges than "
        f"the enacted plan; the {compact['as_equal_profile'][2]} at <= {ENACTED_SPREAD} "
        f"persons average {compact['as_equal_profile'][0]:.1f} cut edges, "
        f"{_pct(compact['as_equal_profile'][1])} at >= {compact['enacted_cut_edges']}, "
        f"against {compact['rest_profile'][0]:.1f} and "
        f"{_pct(compact['rest_profile'][1])} for the other {compact['rest_profile'][2]:,}",
        f"enacted plan: {d['enacted_dem_seats']} D seats ({CONTEST}); closest "
        f"district {d['enacted_closest_district']} at {d['enacted_closest_share']:.6f}",
    ]
    return lines


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args(argv)
    try:
        d = seat_distribution()
    except ValueError as refusal:
        print(f"refused: {refusal}", file=sys.stderr)
        return 1
    for line in summary_lines(d):
        print(line)
    draw(d, args.out)
    print("wrote", args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
