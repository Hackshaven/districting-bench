#!/usr/bin/env python3
"""Figure: Iowa's seat distribution in a neutral ReCom ensemble, with the enacted plan located.

Form: the data's job is magnitude across a handful of discrete outcomes, so
bars, one per possible seat count -- including the ones no draw reached, which
are what "spans 0-2 of 4" is a claim about. One series, so no legend; the title
names it. The enacted plan is a point on this axis, not a category, so it is
marked on the axis and explained in words rather than colour-encoded, and the
words carry the README's caveat with them: the figure travels without the README.

**Every number is recomputed from committed files at draw time** (D-036). The
first version of this script read ``data/results/ia_neutral_seat_distribution.json``,
which is gitignored, so the figure at the top of the README could not be
regenerated by anyone, and its footer carried "43%" as a literal string. It now
reads ``docs/experiment-2/ia-draws-v2.csv.gz`` through Experiment 2's own loader
-- so the sample is the D-035 rectangle, six chains truncated to their common
4,594-draw prefix, with every seed checked against the one its index derives --
and ``docs/phase-2/phase-2-report.json`` for the enacted plan's seat count.

**Seats are read off the efficiency gap, not recounted** (D-039). The draws file
records |efficiency gap| per contest, not seats, and a recount needs the election
returns, which the repository cannot redistribute. With wasted votes counted
against half of each district's votes the gap is exactly ``2V - 1/2 - tau``,
where ``V`` is the statewide two-party Democratic share and ``tau`` the share of
two-party votes cast in districts the Democrats win; ``tau`` is the seat share
``s/k`` when turnout is equal. So each seat count has a level, ``|2V - 1/2 - s/k|``,
and a draw sits off its own level by its turnout imbalance. Folding the sign
away brings the levels closer than ``1/k``: on Iowa the 1- and 2-seat levels,
which hold almost every draw, are 0.083 apart.

:func:`recover_seats` therefore checks two things, and it is the checks, not
nearness, that make the reading a measurement:

* **Sweeps are exact.** A plan the Democrats win none (or all) of sits on its
  level to the vote: the strict-majority threshold the committed gap uses moves
  it by between ``k/2T`` and ``k/T``. Every draw read as a sweep must land in
  that window, so the 0-seat count the enacted-plan comparison rests on is
  verified, not inferred.
* **Every other draw needs a clear margin.** It must sit within half of the
  half-gap of its level, so the middle of every gap must be empty. A 1-seat plan
  is misread as 2 only if its one Democratic district casts over 31% of the
  state's two-party votes against an equal-turnout 25%, four times the largest
  imbalance in these draws; anything between that and the margin is refused,
  not assigned.

The chains are drawn, not only the pool: six chains that disagree about the
2-seat share by 17 points are the uncertainty a pooled bar hides. Whiskers are
two Monte Carlo standard errors, from each share's own effective sample size.
"""
from __future__ import annotations

